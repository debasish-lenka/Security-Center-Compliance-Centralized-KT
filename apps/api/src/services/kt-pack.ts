import { extname } from 'path';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import Jimp from 'jimp';
import { strToU8, zipSync } from 'fflate';
import { formatWhen, latin, watermarkPdf } from './watermark.js';

// "KT pack": the files of a project put together in one file, in the order they were uploaded,
// each marked with who uploaded it and when.

export type Group = 'image' | 'pdf' | 'word' | 'excel' | 'other';

export function groupOf(storageKey: string, mimeType: string): Group {
  const ext = extname(storageKey).toLowerCase();
  if (mimeType.startsWith('image/') || ['.png', '.jpg', '.jpeg', '.gif', '.bmp', '.webp', '.tif', '.tiff'].includes(ext)) return 'image';
  if (ext === '.pdf' || mimeType === 'application/pdf') return 'pdf';
  if (['.doc', '.docx', '.odt', '.rtf'].includes(ext)) return 'word';
  if (['.xls', '.xlsx', '.xlsm', '.csv', '.ods'].includes(ext)) return 'excel';
  return 'other';
}

export interface Source {
  id: string;
  name: string;
  originalName: string;
  storageKey: string;
  mimeType: string;
  createdAt: Date;
  uploader: string;
}
export interface Built { buffer: Buffer; included: Source[]; skipped: { name: string; reason: string }[] }
interface Who { name: string; email: string }

const A4 = { w: 595, h: 842 };
const when = (d: Date) => formatWhen(new Date(d));

async function cover(pdf: PDFDocument, title: string, project: string, who: Who, sources: Source[], extra: string) {
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const page = pdf.addPage([A4.w, A4.h]);
  let y = A4.h - 90;
  const line = (t: string, size: number, f = font, color = rgb(0.1, 0.1, 0.15)) => { page.drawText(latin(t).slice(0, 95), { x: 50, y, size, font: f, color }); y -= size + 8; };
  line(title, 26, bold);
  line(project, 16, font, rgb(0.05, 0.45, 0.55));
  y -= 10;
  line(`Generated by ${who.name} (${who.email})`, 11);
  line(`Generated on ${formatWhen(new Date())}`, 11);
  line(extra, 11);
  y -= 14;
  line('Contents', 13, bold);
  for (const [i, s] of sources.slice(0, 38).entries()) line(`${i + 1}. ${s.name}  -  ${s.uploader}  -  ${when(s.createdAt)}`, 8.5);
  if (sources.length > 38) line(`... and ${sources.length - 38} more`, 8.5);
}

// Every image on its own page, top to bottom in upload order, with the uploader and time under it
export async function imagesPdf(project: string, who: Who, sources: Source[], read: (key: string) => Promise<Buffer>): Promise<Built> {
  const pdf = await PDFDocument.create();
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const included: Source[] = [];
  const skipped: Built['skipped'] = [];
  const pages: { s: Source; img: Awaited<ReturnType<PDFDocument['embedPng']>> }[] = [];

  for (const s of sources) {
    try {
      const bytes = await read(s.storageKey);
      const ext = extname(s.storageKey).toLowerCase();
      let img;
      try {
        if ((ext === '.jpg' || ext === '.jpeg') && bytes.length < 4_000_000) img = await pdf.embedJpg(bytes);
        else if (ext === '.png' && bytes.length < 3_000_000) img = await pdf.embedPng(bytes);
      } catch {
        img = undefined; // a JPEG / PNG variant the PDF library cannot take as it is: re-encode below
      }
      if (!img) {
        // gif, bmp, tiff, very large pictures and odd JPEG / PNG variants: decode, shrink and re-encode as PNG
        const j = await Jimp.read(bytes);
        if (j.getWidth() > 1800) j.resize(1800, Jimp.AUTO);
        img = await pdf.embedPng(await j.getBufferAsync(Jimp.MIME_PNG));
      }
      pages.push({ s, img });
      included.push(s);
    } catch {
      skipped.push({ name: s.name, reason: 'this picture format cannot be put in a PDF (webp and some others)' });
    }
  }

  await cover(pdf, 'KT pack: images', project, who, included, `${included.length} images from ${new Set(included.map((s) => s.uploader)).size} people`);
  const maxW = A4.w - 80, maxH = 620;
  pages.forEach(({ s, img }, i) => {
    const page = pdf.addPage([A4.w, A4.h]);
    page.drawText(latin(`${i + 1} of ${pages.length}   ${s.name}`).slice(0, 90), { x: 40, y: A4.h - 40, size: 9, font, color: rgb(0.4, 0.4, 0.4) });
    const scale = Math.min(maxW / img.width, maxH / img.height, 3);
    const w = img.width * scale, h = img.height * scale;
    const top = A4.h - 60;
    page.drawImage(img, { x: (A4.w - w) / 2, y: top - h, width: w, height: h });
    const capY = top - h - 22;
    page.drawText(latin(`Uploaded by ${s.uploader}`), { x: 40, y: capY, size: 12, font: bold, color: rgb(0.1, 0.1, 0.15) });
    page.drawText(latin(`${when(s.createdAt)}   |   ${s.originalName}`).slice(0, 100), { x: 40, y: capY - 16, size: 9, font, color: rgb(0.3, 0.3, 0.35) });
  });

  const raw = Buffer.from(await pdf.save());
  const buffer = await watermarkPdf(raw, `CONFIDENTIAL - ${project}`);
  return { buffer, included, skipped };
}

// All the PDF documents joined into one PDF; each page says who made it and when
export async function documentsPdf(project: string, who: Who, sources: Source[], read: (key: string) => Promise<Buffer>): Promise<Built> {
  const out = await PDFDocument.create();
  const font = await out.embedFont(StandardFonts.Helvetica);
  const included: Source[] = [];
  const skipped: Built['skipped'] = [];
  const marks: (string | null)[] = [];
  const parts: { s: Source; src: PDFDocument }[] = [];
  for (const s of sources) {
    try {
      parts.push({ s, src: await PDFDocument.load(await read(s.storageKey)) });
      included.push(s);
    } catch {
      skipped.push({ name: s.name, reason: 'the PDF is damaged or protected' });
    }
  }
  await cover(out, 'KT pack: documents (PDF)', project, who, included, `${included.length} documents from ${new Set(included.map((s) => s.uploader)).size} people`);
  marks.push(null);
  for (const { s, src } of parts) {
    for (const p of await out.copyPages(src, src.getPageIndices())) { out.addPage(p); marks.push(`Prepared by ${s.uploader} - ${when(s.createdAt)}`); }
  }
  out.getPages().forEach((page, i) => {
    const m = marks[i];
    if (!m) return;
    const t = latin(m);
    page.drawText(t, { x: Math.max(8, (page.getWidth() - font.widthOfTextAtSize(t, 8)) / 2), y: 32, size: 8, font, color: rgb(0.2, 0.2, 0.2) });
  });
  const raw = Buffer.from(await out.save());
  const buffer = await watermarkPdf(raw, `CONFIDENTIAL - ${project}`);
  return { buffer, included, skipped };
}

const safe = (s: string) => s.replace(/[\\/:*?"<>|]/g, '_').slice(0, 90);
const csv = (v: string) => `"${v.replace(/"/g, '""')}"`;

// Word, Excel and other files cannot be merged into one Word / Excel file reliably, so they are kept
// intact in one ZIP, named by order, person and date, with a contents list.
export async function zipBundle(project: string, who: Who, sources: Source[], read: (key: string) => Promise<Buffer>): Promise<Built> {
  const files: Record<string, Uint8Array> = {};
  const included: Source[] = [];
  const skipped: Built['skipped'] = [];
  const rows = ['No,File,Uploaded by,Uploaded on'];
  for (const s of sources) {
    try {
      const bytes = await read(s.storageKey);
      const n = String(included.length + 1).padStart(2, '0');
      files[`${n} - ${safe(s.uploader)} - ${new Date(s.createdAt).toISOString().slice(0, 10)} - ${safe(s.originalName)}`] = new Uint8Array(bytes);
      rows.push([n, csv(s.originalName), csv(s.uploader), csv(when(s.createdAt))].join(','));
      included.push(s);
    } catch {
      skipped.push({ name: s.name, reason: 'the file could not be read' });
    }
  }
  files['contents.csv'] = strToU8(`﻿${rows.join('\r\n')}\r\n`);
  files['README.txt'] = strToU8(`KT pack for ${project}\r\nGenerated by ${who.name} (${who.email}) on ${formatWhen(new Date())}\r\n${included.length} files, in the order they were uploaded.\r\n`);
  return { buffer: Buffer.from(zipSync(files, { level: 6 })), included, skipped };
}
